test('modified input shortcuts preserve native editing and composing text', async ({ page }) => {
  await page.goto('./ascension/')
  const input = page.getByRole('searchbox')
  await input.fill('Soul')
  await input.evaluate((element) => (element as HTMLInputElement).setSelectionRange(2, 2))
  await input.press('Shift+ArrowDown')
  await expect(input).toBeFocused()
  expect(await input.evaluate((element) => ({ start: (element as HTMLInputElement).selectionStart, end: (element as HTMLInputElement).selectionEnd }))).toEqual({ start: 2, end: 4 })
  for (const key of ['Control+ArrowDown', 'Alt+ArrowUp', 'Meta+ArrowUp', 'Shift+Enter']) {
    await input.press(key)
    await expect(input).toBeFocused()
    await expect(page.getByRole('region', { name: 'Visible upgrade results', exact: true })).toBeVisible()
  }
  expect(await input.evaluate((element) => {
    const event = new KeyboardEvent('keydown', { key: 'ArrowDown', bubbles: true, cancelable: true, isComposing: true })
    element.dispatchEvent(event)
    return event.defaultPrevented
  })).toBe(false)
  await expect(input).toBeFocused()
  await input.press('ArrowDown')
  const first = page.locator('.search-result').first()
  await expect(first).toBeFocused()
  await first.press('Shift+ArrowDown')
  await expect(first).toBeFocused()
  expect(await page.evaluate(() => window.__readMapProfileText('idle-slayer-ascension-map.profile.v1'))).toBeNull()
})

test('deferred reopening cannot steal later Tab focus or override a newer candidate', async ({ page }) => {
  await page.goto('./ascension/')
  const input = page.getByRole('searchbox')
  await input.fill('Soul')
  await input.press('Escape')
  await expect(page.getByRole('region', { name: 'Visible upgrade results', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Toggle search results', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await page.clock.install()
  await page.clock.pauseAt(await page.evaluate(() => Date.now()) + 1000)
  await input.press('ArrowDown')
  await expect(page.locator('.search-result').first()).toBeVisible()
  await expect(input).toBeFocused()
  await input.press('Tab')
  const close = await closeAfterNativeTab(page, true)
  await page.clock.runFor(64)
  await expect(close).toBeFocused()

  await close.press('Escape')
  await expect(input).toBeFocused()
  await input.press('ArrowDown')
  await input.press('ArrowUp')
  await expect(page.locator('.search-result').last()).toBeFocused()
  await page.clock.runFor(64)
  await expect(page.locator('.search-result').last()).toBeFocused()

  await page.keyboard.press('Escape')
  await input.press('ArrowDown')
  await input.fill('PRIVATE UNMATCHED FIXTURE')
  await page.clock.runFor(64)
  await expect(input).toBeFocused()
  await expect(page.locator('.search-result')).toHaveCount(0)
  await expect(page.locator('[aria-current="true"].search-result')).toHaveCount(0)
  expect(await page.evaluate(() => window.__readMapProfileText('idle-slayer-ascension-map.profile.v1'))).toBeNull()
})


