test('arrow selection opens a non-first result through native button focus', async ({ page }, info) => {
  await page.goto('./ascension/')
  const input = page.getByRole('searchbox')
  await input.fill('Soul')
  const region = page.getByRole('region', { name: 'Visible upgrade results', exact: true })
  const rows = region.locator('.search-result')
  const count = await rows.count()
  expect(count).toBeGreaterThan(2)
  const chosen = rows.nth(1), id = await chosen.getAttribute('data-upgrade-id'), title = await chosen.locator('.discovery-title').innerText()
  await expect(page.getByRole('button', { name: 'Toggle search results', exact: true })).toHaveAttribute('aria-expanded', 'true')
  await expect(input).toHaveAttribute('aria-controls', (await region.getAttribute('id'))!)
  await expect(page.getByRole('button', { name: 'Toggle search results', exact: true })).toHaveAttribute('aria-controls', (await region.getAttribute('id'))!)
  const status = page.getByRole('status').filter({ hasText: 'Search results open.' })
  await expect(status).toHaveText(`Search results open. ${count} visible results.`)
  await expect(input).toHaveAccessibleDescription(new RegExp(`^Search results open[.] ${count} visible results[.]`))
  await input.press('ArrowDown')
  await expect(rows.nth(0)).toBeFocused()
  await focusedDiscoveryTitleIsReadable(page)
  await page.keyboard.press('End')
  await expect(rows.last()).toBeFocused()
  await focusedDiscoveryTitleIsReadable(page)
  await page.keyboard.press('Home')
  await expect(rows.nth(0)).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(chosen).toBeFocused()
  await expect(chosen).toHaveAttribute('aria-current', 'true')
  await expect(region.locator('[aria-current="true"]')).toHaveCount(1)
  await expect(chosen).toHaveAccessibleDescription(new RegExp(`Candidate 2 of ${count} visible results[.]$`))
  const toggleBox = await page.getByRole('button', { name: 'Toggle search results', exact: true }).boundingBox()
  expect(toggleBox!.width).toBeGreaterThanOrEqual(44); expect(toggleBox!.height).toBeGreaterThanOrEqual(44)
  await page.screenshot({ path: info.outputPath('keyboard-candidate.png') })
  await page.keyboard.press('Enter')
  await expect(region).toHaveCount(0)
  await expect(page.locator('.details h2')).toHaveText(title)
  await expect(page.locator('.details h2')).toBeFocused()
  await expect(page.locator('.react-flow__node.selected')).toHaveAttribute('data-id', id!)
  expect(await page.evaluate(() => window.__readMapProfileText('idle-slayer-ascension-map.profile.v1'))).toBeNull()
})

test('text editing, native Tab and Space remain available alongside arrow selection', async ({ page }) => {
  await page.goto('./ascension/')
  const input = page.getByRole('searchbox')
  await input.fill('Soul')
  await input.press('Home')
  await expect(input).toBeFocused()
  expect(await input.evaluate((element) => (element as HTMLInputElement).selectionStart)).toBe(0)
  await input.press('End')
  expect(await input.evaluate((element) => (element as HTMLInputElement).selectionStart)).toBe(4)
  await input.press('ArrowLeft')
  await expect(input).toBeFocused()
  expect(await input.evaluate((element) => (element as HTMLInputElement).selectionStart)).toBe(3)
  await input.press('Tab')
  await closeAfterNativeTab(page)
  await page.keyboard.press('Tab')
  await expect(page.getByRole('combobox', { name: 'Progress state', exact: true })).toBeFocused()
  const rows = page.locator('.search-result'), secondTitle = await rows.nth(1).locator('.discovery-title').innerText()
  await page.keyboard.press('Tab'); await expect(rows.nth(0)).toBeFocused()
  await page.keyboard.press('Tab'); await expect(rows.nth(1)).toBeFocused()
  await focusedDiscoveryTitleIsReadable(page)
  await page.keyboard.press('Space')
  await expect(page.locator('.details h2')).toHaveText(secondTitle)
})

test('Escape and disclosure expose closed state, then arrows reopen candidates', async ({ page }) => {
  await page.goto('./ascension/')
  const input = page.getByRole('searchbox'), toggle = page.getByRole('button', { name: 'Toggle search results', exact: true })
  await input.fill('Soul'); await input.press('ArrowDown')
  await page.keyboard.press('Escape')
  await expect(input).toBeFocused()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(toggle).not.toHaveAttribute('aria-controls')
  await expect(input).not.toHaveAttribute('aria-controls')
  await expect(page.getByRole('status').filter({ hasText: 'Search results closed.' })).toBeVisible()
  await input.press('ArrowUp')
  await expect(page.locator('.search-result').last()).toBeFocused()
  await focusedDiscoveryTitleIsReadable(page)
  await page.keyboard.press('Escape')
  await input.press('ArrowDown')
  await expect(page.locator('.search-result').first()).toBeFocused()
  await toggle.click()
  await expect(toggle).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByRole('region', { name: 'Visible upgrade results', exact: true })).toHaveCount(0)
})

